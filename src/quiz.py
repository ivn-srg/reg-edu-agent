QUIZ_PROMPT = ChatPromptTemplate.from_messages([
    ("system", QUIZ_SYSTEM),
    ("human", (
        "Сгенерируй тест из {num} вопросов с вариантами ответов(правильный ответ и 3–4 правдоподобных варианта) по теме: {topic}.\n"
        "Ограничивайся информацией в Контексте. Форматируй как пронумерованный список.\n\n"
        "Контекст:\n{context}\n\nВопросы:")),
])


def generate_quiz(topic: str, num: int = 5, history: Optional[List[Dict[str, str]]] = None, similarity_threshold: float = 0.4) -> Dict[str, str]:
    vdb = load_vector_store()
    retriever = vdb.as_retriever(k=12)  # Берем больше для фильтрации
    
    # Проверяем релевантность ТЕКУЩЕЙ темы через semantic gating
    # Разрешаем разные темы в рамках одного диалога, но только в рамках материалов
    raw_docs = retriever.invoke(topic)
    context_docs = semantic_gating(topic, raw_docs, threshold=similarity_threshold)
    context_docs = context_docs[:6]  # Ограничиваем
    
    # Проверяем, есть ли релевантные документы
    if not context_docs or len(context_docs) == 0:
        return {
            "topic": topic,
            "questions": "Такой информации нет в предоставленных материалах. Попробуйте задать другой вопрос"
        }
    
    context = "\n---\n".join(d.page_content for d in context_docs)

    # Формируем историю сообщений (ограниченную для скорости)
    # История помогает модели понять контекст, но не ограничивает темы
    messages = [SystemMessage(content=QUIZ_SYSTEM)]
    
    if history:
        recent_history = history[-2:] if len(history) > 2 else history
        for msg in recent_history:
            if msg["role"] == "user":
                messages.append(HumanMessage(content=msg["content"]))
            elif msg["role"] == "assistant":
                messages.append(AIMessage(content=msg["content"]))
    
    # Добавляем текущий запрос с контекстом
    prompt_text = f"""Сгенерируй тест из {num} вопросов с вариантами ответов (правильный ответ и 3–4 правдоподобных варианта) по теме: {topic}.

ОБЯЗАТЕЛЬНО используй Markdown форматирование:
- Каждый вопрос начинай с ### и номера
- Варианты ответов оформляй списком с -
- Буквы вариантов выделяй **жирным**

Пример формата:
### 1. Текст вопроса?

- **а)** Вариант 1
- **б)** Вариант 2
- **в)** Вариант 3
- **г)** Вариант 4

Контекст:
{context}

Вопросы:"""
    messages.append(HumanMessage(content=prompt_text))
    
    # Вызываем LLM
    llm = get_chat_llm()
    response = llm.invoke(messages)
    out = response.content if hasattr(response, 'content') else str(response)
    
    return {"topic": topic, "questions": out}

